export function newElement(
  kind: ElementKind,
  selection = defaultSelection,
): KitchenElement {
  const t = templates.find((x) => x.kind === kind)!;
  return {
    id: uid(),
    kind,
    width: t.width,
    height: t.height,
    depth: t.depth,
    quantity: 1,
    doors: t.doors,
    drawers: t.drawers,
    shelves: t.shelves,
    locked: false,
    selection: { ...selection },
    extra: 0,
    note: "",
  };
}
