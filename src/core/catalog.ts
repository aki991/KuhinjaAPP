export function findProduct(
  prices: Product[],
  category: Category,
  tier?: Tier,
  kind?: string,
  preferred?: string,
): Product | undefined {
  const a = prices.filter(
    (p) =>
      p.active &&
      p.category === category &&
      (!tier || p.tier === tier) &&
      (!kind || p.kind === kind),
  );
  return a.find((p) => p.supplier === preferred) || a[0];
}
